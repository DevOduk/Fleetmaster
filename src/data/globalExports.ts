export const yearsOfManufacture = (
  providedStart?: number | null,
  end: number = new Date().getFullYear(),
): number[] => {
  const start =
    providedStart === undefined || providedStart === null
      ? 1950
      : providedStart;
  const years: number[] = [];

  for (let i = start; i <= end; i++) {
    years.push(i);
  }

  return years;
};

